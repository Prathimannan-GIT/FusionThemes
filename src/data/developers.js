// Helper to authenticate developer credentials
export const authenticateDeveloper = (loginId, password) => {
  if (!loginId || !password) return null;
  const trimmedId = loginId.trim().toLowerCase();
  const trimmedPass = password.trim();

  // Find matching developer by loginId
  const developer = DEVELOPERS.find(
    (dev) => dev.loginId.toLowerCase() === trimmedId || dev.id.toLowerCase() === trimmedId
  );

  if (developer && developer.password === trimmedPass) {
    return developer;
  }
  return null;
};

// Helper to get developer profile by ID
export const getDeveloperById = (developerId) => {
  if (!developerId) return null;
  return DEVELOPERS.find(
    (dev) => dev.id.toLowerCase() === developerId.toLowerCase() || dev.loginId.toLowerCase() === developerId.toLowerCase()
  ) || null;
};

